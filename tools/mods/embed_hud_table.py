"""Turns the HUD placement table of the widescreen fix (third_party/widescreen/NFSUnderground2.WidescreenFix.dat) into
mods_hud_table.inc, which mods_rendering.cpp compiles in: nothing from the mod is read at run time.

    python tools/mods/embed_hud_table.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
rows = []
for line in (ROOT / "third_party/widescreen/NFSUnderground2.WidescreenFix.dat").read_text(encoding="utf-8", errors="replace").splitlines():
    if not line.strip() or line.lstrip().startswith("#"):
        continue
    parts = line.split()
    if len(parts) < 5:
        continue
    try:
        x, y, ox, oy = (float(v) for v in parts[1:5])
    except ValueError:
        continue
    rows.append((parts[0], x, y, ox, oy))

def f(v):
    text = repr(v)
    return text + "f"

out = ["// Generated by tools/mods/embed_hud_table.py from the HUD table of the NFSU2 Widescreen Fix (MIT, ThirteenAG and contributors).",
       "// {x, y, offset_x, offset_y}: a HUD element drawn at (x, y) in the 640x480 layout moves by the widescreen offset (+ offset_x, + offset_y)."]
for name, x, y, ox, oy in rows:
    out.append(f"{{{f(x)}, {f(y)}, {f(ox)}, {f(oy)}}},  // {name}")
(ROOT / "mods_hud_table.inc").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
print(len(rows), "entries")
