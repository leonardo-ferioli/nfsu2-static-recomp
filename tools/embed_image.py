"""Generate image_data.cpp: the guest image blocks (export/memory_*.bin) as data inside the launcher.

    python tools/embed_image.py <platform_image.inc> <export dir> <output.cpp>

With this data in the program the launcher does not need SPEED2.EXE at run time. The blocks are the same bytes that the launcher
would read from the user's SPEED2.EXE; the platform still checks every block against its SHA-256 before using it.
"""
import re
import sys
from pathlib import Path

inc, export, out = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
blocks = re.findall(r'\{0x([0-9a-f]+),\s*(\d+),\s*"([^"]+)"', inc.read_text())
if not blocks:
    raise SystemExit("no image blocks found in " + str(inc))
lines = ["// Generated by tools/embed_image.py. The guest image blocks, as data.", '#include "native32.hpp"', "namespace {"]
table = []
for index, (base, size, name) in enumerate(blocks):
    path = export / name
    if path.stat().st_size != int(size):
        raise SystemExit(f"{path} has {path.stat().st_size} bytes, expected {size}")
    lines.append(f"const uint8_t block_{index}[] = {{")
    lines.append(f'#embed "{path.resolve().as_posix()}"')
    lines.append("};")
    table.append(f"    {{0x{base}u, {size}u, block_{index}}},")
lines.append("}")
lines.append("extern const nfsu2raw::EmbeddedImageBlock embedded_image_blocks[];")
lines.append("extern const unsigned embedded_image_block_count;")
lines.append("const nfsu2raw::EmbeddedImageBlock embedded_image_blocks[] = {")
lines.extend(table)
lines.append("};")
lines.append(f"const unsigned embedded_image_block_count = {len(blocks)};")
out.parent.mkdir(parents=True, exist_ok=True)
text = "\n".join(lines) + "\n"
if not out.exists() or out.read_text() != text:
    out.write_text(text)
