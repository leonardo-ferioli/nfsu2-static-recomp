"""Derive guest image/import contracts from the identified local PE, never execute it."""
import hashlib
import json
from pathlib import Path
import pefile

ROOT = Path(__file__).resolve().parents[1]
manifest = json.loads((ROOT / 'export/manifest.json').read_text())
binary = ROOT.parent / 'binaries/SPEED2.EXE'
assert hashlib.sha256(binary.read_bytes()).hexdigest() == manifest['input_sha256']
pe = pefile.PE(str(binary))
lines = ['// Generated by tools/platform_metadata.py; guest addresses only.',
         f'constexpr uint32_t image_base = 0x{pe.OPTIONAL_HEADER.ImageBase:x};',
         f'constexpr uint32_t image_size = 0x{pe.OPTIONAL_HEADER.SizeOfImage:x};',
         f'constexpr uint32_t entry_point = 0x{pe.OPTIONAL_HEADER.ImageBase + pe.OPTIONAL_HEADER.AddressOfEntryPoint:x};',
         f'constexpr uint32_t stack_size = 0x{pe.OPTIONAL_HEADER.SizeOfStackReserve:x};',
         'constexpr ImageBlock image_blocks[] = {']
for block in manifest['memory']:
    if block['name'] == 'tdb':
        continue
    data = (ROOT / 'export' / block['file']).read_bytes()
    assert len(data) == block['size']
    lines.append(f'{{0x{block["start"]:x}, {block["size"]}, "{block["file"]}", "{hashlib.sha256(data).hexdigest()}"}},')
lines += ['};', 'constexpr Import imports[] = {']
inventory = []
for dll in pe.DIRECTORY_ENTRY_IMPORT:
    for item in dll.imports:
        name = item.name.decode() if item.name else f'#{item.ordinal}'
        library = dll.dll.decode()
        token = 0xf0000000 + len(inventory) * 16
        lines.append(f'{{0x{item.address:x}, 0x{token:x}, "{library}", "{name}"}},')
        inventory.append(dict(iat=item.address, token=token, dll=library, name=name))
lines.append('};')
target = ROOT / 'generated/platform_image.inc'
contents = '\n'.join(lines) + '\n'
if not target.exists() or target.read_text() != contents:
    target.write_text(contents)
(ROOT / 'export/platform_imports.json').write_text(json.dumps(dict(input_sha256=manifest['input_sha256'], entry_point=pe.OPTIONAL_HEADER.ImageBase + pe.OPTIONAL_HEADER.AddressOfEntryPoint, imports=inventory), indent=2) + '\n')
print(f'Generated {len(inventory)} import bindings, {len(manifest["memory"])-1} image blocks')
