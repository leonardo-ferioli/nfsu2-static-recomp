"""List the distinct x87 encodings the game uses, as X-macro lines for x87v_tests.cpp.

    python tools/list_x87_encodings.py > x87v_encodings.inc

Memory forms are written with ModRM mod=00 rm=000 (operand at [eax]); register forms with their full ModRM."""
import collections
import gzip
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
text = (root / "export/memory_401000.bin").read_bytes()
seen = collections.OrderedDict()
with gzip.open(root / "export/instructions.jsonl.gz", "rt", encoding="utf-8") as source:
    for line in source:
        r = json.loads(line)
        m = r["asm"].split()[0] if r["asm"] else ""
        if not m.startswith("F") or m == "FEMMS":
            continue
        raw = text[r["a"] - 0x401000:r["a"] - 0x401000 + r["n"]]
        body = raw[1:] if raw[:1] == b"\x9b" else raw
        if len(body) < 2 or not 0xd8 <= body[0] <= 0xdf:
            continue
        modrm = body[1]
        key = (body[0], modrm & 0x38 if modrm >> 6 != 3 else modrm)
        seen.setdefault(key, m)
print("// generated by tools/list_x87_encodings.py: distinct x87 encodings of the game (opcode, ModRM; memory forms use mod=00 rm=0)")
for (op, modrm), m in sorted(seen.items()):
    print(f"E(0x{op:02x},0x{modrm:02x}) /* {m} */")
